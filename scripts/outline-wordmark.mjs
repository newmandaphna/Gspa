// Outlines the wordmark letters (GUN, SPA, and the tagline) into SVG path data
// from the Montserrat font files shipped by @fontsource/montserrat, so the site
// never has to load the brand face. Writes src/components/wordmark-paths.ts,
// which is committed; rerun only if the lockup changes.
//
//   node scripts/outline-wordmark.mjs
//
// Layout mirrors the CSS the wordmark used before: Montserrat 500 with 0.22em
// tracking for the two words, Montserrat 600 with 0.14em tracking for the
// tagline. Units are 1/1000 em (Montserrat's unitsPerEm).

import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const opentype = require("opentype.js");

function load(file) {
  const buf = readFileSync(require.resolve(`@fontsource/montserrat/files/${file}`));
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
}

const medium = load("montserrat-latin-500-normal.woff");
const semibold = load("montserrat-latin-600-normal.woff");

/** Returns path data for `text` set on a baseline at y, plus the advance it consumed. */
function outline(font, text, x, y, size, trackingEm) {
  const scale = size / font.unitsPerEm;
  const tracking = trackingEm * size;
  const glyphs = font.stringToGlyphs(text);
  let cursor = x;
  let d = "";
  for (let i = 0; i < glyphs.length; i++) {
    const g = glyphs[i];
    const p = g.getPath(cursor, y, size);
    d += p.toPathData(1);
    let adv = g.advanceWidth * scale;
    if (i < glyphs.length - 1) adv += font.getKerningValue(g, glyphs[i + 1]) * scale + tracking;
    cursor += adv;
  }
  return { d, width: cursor - x };
}

const SIZE = 1000;
const capHeight = (medium.tables.os2?.sCapHeight ?? 700) * (SIZE / medium.unitsPerEm);

const gun = outline(medium, "GUN", 0, capHeight, SIZE, 0.22);
const spa = outline(medium, "SPA", 0, capHeight, SIZE, 0.22);

const tagSize = 1000;
const tagCap = (semibold.tables.os2?.sCapHeight ?? 700) * (tagSize / semibold.unitsPerEm);
const ready = outline(semibold, "READY? AIM. ", 0, tagCap, tagSize, 0.14);
const relax = outline(semibold, "RELAX!", ready.width, tagCap, tagSize, 0.14);

const out = `// Generated by scripts/outline-wordmark.mjs from Montserrat (OFL). Do not edit by hand.
// Units: 1/1000 em. Caps sit on a baseline at y = CAP_HEIGHT, cap tops at y = 0.

export const CAP_HEIGHT = ${Math.round(capHeight)};

/** "GUN", Montserrat 500, 0.22em tracking. */
export const GUN = { width: ${Math.round(gun.width)}, d: ${JSON.stringify(gun.d)} };

/** "SPA", Montserrat 500, 0.22em tracking. */
export const SPA = { width: ${Math.round(spa.width)}, d: ${JSON.stringify(spa.d)} };

/** "READY? AIM. RELAX!", Montserrat 600, 0.14em tracking, split so the last word can take the gold. */
export const TAGLINE = {
  width: ${Math.round(ready.width + relax.width)},
  ready: ${JSON.stringify(ready.d)},
  relax: ${JSON.stringify(relax.d)},
};
`;
writeFileSync(resolve(ROOT, "src/components/wordmark-paths.ts"), out);
console.log(`wordmark-paths.ts written: GUN ${Math.round(gun.width)}, SPA ${Math.round(spa.width)}, tagline ${Math.round(ready.width + relax.width)} units wide`);
