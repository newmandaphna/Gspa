// Builds src/lib/media/manifest.ts from the photographs in public/media.
//
// Runs as "prebuild" (see package.json) and can be run by hand:
//   node scripts/media-manifest.mjs
//
// For every hero_photo_01.jpg (or .jpeg, .png) it records the slot key
// HERO_PHOTO_01, the pixel size, a 12 px blurDataURL for the placeholder, and,
// when hero_photo_01-portrait.jpg sits beside it, the portrait companion for
// phones. ImageSlot reads the manifest, so dropping a correctly named file in
// public/media is the whole integration. Safe when the folder is empty or
// missing: it writes an empty manifest and exits 0.

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MEDIA_DIR = resolve(ROOT, "public/media");
const OUT = resolve(ROOT, "src/lib/media/manifest.ts");
const PORTRAIT_SUFFIX = "-portrait";
const BLUR_PX = 12;
const EXT = /\.(jpe?g|png)$/i;

async function main() {
  const files = existsSync(MEDIA_DIR) ? readdirSync(MEDIA_DIR).filter((f) => EXT.test(f)).sort() : [];

  /** @type {Map<string, {landscape?: string, portrait?: string}>} */
  const bySlot = new Map();
  for (const file of files) {
    const stem = file.replace(EXT, "");
    const portrait = stem.endsWith(PORTRAIT_SUFFIX);
    const key = (portrait ? stem.slice(0, -PORTRAIT_SUFFIX.length) : stem).toUpperCase();
    if (!/^[A-Z0-9_]+$/.test(key)) {
      console.warn(`[media] skipping ${file}: name it after the slot id, for example hero_photo_01.jpg`);
      continue;
    }
    const entry = bySlot.get(key) ?? {};
    entry[portrait ? "portrait" : "landscape"] = file;
    bySlot.set(key, entry);
  }

  let sharp = null;
  if (bySlot.size) {
    try {
      sharp = (await import("sharp")).default;
    } catch (err) {
      console.error("[media] sharp is not installed; run npm install", err);
      process.exit(1);
    }
  }

  async function describe(file) {
    const abs = resolve(MEDIA_DIR, file);
    const image = sharp(readFileSync(abs));
    const meta = await image.metadata();
    const width = meta.width ?? 0;
    const height = meta.height ?? 0;
    if (!width || !height) throw new Error(`[media] could not read the size of ${file}`);
    const blur = await image
      .clone()
      .resize({ width: BLUR_PX, height: Math.max(1, Math.round((BLUR_PX * height) / width)), fit: "fill" })
      .jpeg({ quality: 60 })
      .toBuffer();
    return { src: `/media/${file}`, width, height, blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}` };
  }

  const entries = [];
  for (const [key, { landscape, portrait }] of bySlot) {
    if (!landscape) {
      console.warn(`[media] ${key}: only a ${PORTRAIT_SUFFIX} file exists; add the landscape export too`);
      continue;
    }
    const entry = await describe(landscape);
    if (portrait) entry.portrait = await describe(portrait);
    entries.push([key, entry]);
  }

  const body = entries.map(([key, entry]) => `  ${key}: ${JSON.stringify(entry, null, 2).replace(/\n/g, "\n  ")},`).join("\n");
  const source = `// Generated by scripts/media-manifest.mjs from public/media. Do not edit by hand.
// Add a photo named after its slot id (hero_photo_01.jpg, plus hero_photo_01-portrait.jpg
// for phones) and rerun the script, or let "prebuild" do it.

export type MediaImage = {
  src: string;
  width: number;
  height: number;
  /** 12 px JPEG, inlined as the placeholder while the real file streams in. */
  blurDataURL: string;
};

export type MediaEntry = MediaImage & {
  /** A 4:5 or taller export for portrait viewports, when the shoot supplied one. */
  portrait?: MediaImage;
};

export const MEDIA_MANIFEST: Record<string, MediaEntry> = {
${body}
};

export function mediaFor(slot: string): MediaEntry | undefined {
  return MEDIA_MANIFEST[slot.toUpperCase()];
}
`;

  mkdirSync(dirname(OUT), { recursive: true });
  const previous = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (previous !== source) writeFileSync(OUT, source);
  console.log(`[media] ${entries.length} photo${entries.length === 1 ? "" : "s"} in the manifest${files.length ? "" : " (public/media is empty)"}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
